// me-index.ts: the host index taking a full first publish of one ME view (brief 17 item 8), rolled back.
import { connect, PgStore, publish } from "@cruba/crubal-postgres";
import type { Pool } from "@cruba/crubal-postgres";
import { Index } from "../src/indexer.ts";
const pool = connect(process.env.CRUBAL_PG_URL ?? "postgres:///postgres", process.env.CRUBAL_PG_SCHEMA ?? "crubal_me");
const owner = "mediaencyclopedia.com";
const name = process.argv[2] ?? "channelStatus";
const s = new PgStore(pool, owner, { allowUnsigned: true });
const p = (await s.projecting())!;
const v = p.views.views.get(name)!;
const client = await pool.connect();
const ms = (t: bigint) => Number((process.hrtime.bigint() - t) / 1000n) / 1000;
await client.query("begin");
await client.query("delete from projections where owner=$1 and view=$2", [owner, name]);
await client.query("delete from projection_stream where owner=$1 and view=$2", [owner, name]);
await client.query("delete from published where owner=$1 and view=$2", [owner, name]);
let t = process.hrtime.bigint();
const entries = await publish(client, owner, p, name);
console.log(`store publish ${ms(t)} ms, ${entries.length} entries`);
await client.query("delete from index_rows where owner=$1 and view=$2", [owner, name]);
await client.query("delete from index_cursors where owner=$1 and view=$2", [owner, name]);
const index = new Index({ query: (sql: string, params?: unknown[]) => client.query(sql, params) } as unknown as Pool);
t = process.hrtime.bigint();
const seq = await index.ingest(owner, name, v.version ?? "", v.show, entries, 0);
console.log(`index ingest ${ms(t)} ms, cursor ${seq}`);
const n = (await client.query("select count(*) from index_rows where owner=$1 and view=$2", [owner, name])).rows[0].count;
console.log(`index rows ${n}`);
await client.query("rollback");
client.release();
await pool.end();
