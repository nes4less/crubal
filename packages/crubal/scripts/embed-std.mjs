#!/usr/bin/env node
// embed-std.mjs: copy the standard packages' text into the engine, so an adopter can check its own packages
// against crubal.com/core, units and party without fetching them. Writes src/units-table.ts (the units
// table, as before) and src/std-packages.ts. Run from packages/crubal: `npm run embed`. A test refuses a
// copy that has drifted from std/.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../../../", import.meta.url));
const here = fileURLToPath(new URL("../", import.meta.url));
const lit = (t) => "`" + t.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${") + "`";
const std = (p) => readFileSync(`${root}std/${p}`, "utf8");

writeFileSync(
  `${here}src/units-table.ts`,
  `// units-table.ts: the standard units table, crubal.com/units, as published in std/units/units.crubal. Generated by\n// \`npm run embed\` in packages/crubal; a test refuses a copy that has drifted from the file.\n\nexport const STANDARD_UNITS = ${lit(std("units/units.crubal"))};\n`,
);

writeFileSync(
  `${here}src/std-packages.ts`,
  `// std-packages.ts: the text of the standard packages (spec 11.7), as published in std/. Generated by
// \`npm run embed\` in packages/crubal; a test refuses a copy that has drifted from the files. An adopter reads
// these into a dictionary before its own packages, as a publish does (11.4).

import { type Dictionary, emptyDictionary, readDefinitions } from "./defs.ts";

/** The standard packages' text, by name: core, units and party. */
export const STANDARD_PACKAGES: { readonly core: string; readonly units: string; readonly party: string } = {
  core: ${lit(std("core/package.crubal"))},
  units: ${lit(std("units/package.crubal"))},
  party: ${lit(std("party/package.crubal"))},
};

/** A dictionary holding the three standard packages' definitions, to read an adopter's packages onto. */
export function standardDefinitions(into: Dictionary = emptyDictionary()): Dictionary {
  for (const text of [STANDARD_PACKAGES.core, STANDARD_PACKAGES.units, STANDARD_PACKAGES.party]) readDefinitions(text, into);
  return into;
}
`,
);
console.log("written src/units-table.ts and src/std-packages.ts");
